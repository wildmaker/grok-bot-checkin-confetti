// Assembles two unpacked extensions:
//   dist/prod  - the shippable build (unverified production profile, fail-closed)
//   dist/test  - identical, except src/profile.js is replaced by the SYNTHETIC test profile
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');

function parseArt(svgText) {
  const viewBox = /viewBox="([^"]+)"/.exec(svgText)[1];
  const head = /<path class="head"[^>]* d="([^"]+)"/.exec(svgText)[1];
  const eyes = [...svgText.matchAll(/<path class="eye"[^>]* d="([^"]+)"/g)].map((m) => m[1]);
  if (!head || eyes.length !== 2) throw new Error('unexpected Grok Bot mark structure');
  return { viewBox, head, eyes };
}

function generatedAssets() {
  const art = parseArt(readFileSync(path.join(root, 'assets/grok-bot-mark.svg'), 'utf8'));
  const css = readFileSync(path.join(root, 'src/overlay.css'), 'utf8');
  return (
    '/* Generated by scripts/build.mjs from assets/grok-bot-mark.svg and src/overlay.css. */\n' +
    '(function (root) {\n' +
    '  root.GrokBotCheckin = Object.assign(root.GrokBotCheckin || {}, {\n' +
    `    botArt: ${JSON.stringify(art)},\n` +
    `    overlayCss: ${JSON.stringify(css)},\n` +
    '  });\n' +
    "})(typeof globalThis !== 'undefined' ? globalThis : this);\n"
  );
}

function assemble(name, { synthetic }) {
  const out = path.join(dist, name);
  mkdirSync(out, { recursive: true });
  const manifest = JSON.parse(readFileSync(path.join(root, 'manifest.json'), 'utf8'));
  if (synthetic) {
    manifest.name = 'SYNTHETIC TEST BUILD - not for use';
    manifest.description = 'Test-only build with a synthetic detection profile. Never distribute.';
  }
  writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  for (const file of readdirSync(path.join(root, 'src'))) {
    if (file.endsWith('.js')) cpSync(path.join(root, 'src', file), path.join(out, file));
  }
  if (synthetic) cpSync(path.join(root, 'test-support/synthetic-profile.js'), path.join(out, 'profile.js'));
  writeFileSync(path.join(out, 'assets.generated.js'), generatedAssets());
  cpSync(path.join(root, 'assets/icons'), path.join(out, 'icons'), { recursive: true });
}

rmSync(dist, { recursive: true, force: true });
assemble('prod', { synthetic: false });
assemble('test', { synthetic: true });
console.log('built dist/prod and dist/test');
